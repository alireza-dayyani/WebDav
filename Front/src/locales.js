export function translate(locale, key, values = {}) {
  return (messages[locale]?.[key] ?? messages.en[key] ?? key).replace(
    /\{(\w+)\}/g,
    (_, name) => values[name] ?? `{${name}}`,
  );
}
export function normalizeSearch(value) {
  return value
    .normalize("NFKC")
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .toLocaleLowerCase();
}
